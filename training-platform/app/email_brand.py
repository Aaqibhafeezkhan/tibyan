"""Branded e-mail: plain text + inline-CSS HTML from one plain-text body.

Mail clients ignore <style> blocks and CSS variables, so every colour here is
an inline literal copied from app/static/tokens.css (the «هندسي» palette).
The logo is the raster copy of the app logo (app/static/brand/logo-cream.png,
generated by brand/gen_assets.py); clients do not render SVG.
"""
from __future__ import annotations

import html
import re

from .templating import FACEBOOK_URL, INSTAGRAM_URL

LOGO_URL = "https://altibyan.app/static/brand/logo-cream.png"
SITE_URL = "https://altibyan.app"

TEAL = "#0F6660"
TEAL_LO = "#0A4F4A"
CREAM = "#F6F1E8"
SURFACE = "#FFFCF6"
INK = "#1E1915"
INK_2 = "#5E5A52"
LINE = "#E2D9C8"
GOLD = "#D9B266"
FONT = "'Changa', 'IBM Plex Sans Arabic', 'Segoe UI', Tahoma, Arial, sans-serif"

_URL = re.compile(r"https?://[^\s<>«»()]+[^\s<>«»().,:;!?،]")
_STEP = re.compile(r"^(\d+)\.\s+(.*)$")

FOLLOW = {"ar": "تابعنا على فيسبوك", "en": "Follow us on Facebook"}
FOLLOW_IG = {"ar": "تابعنا على إنستجرام", "en": "Follow us on Instagram"}


def _inline(text: str) -> str:
    """Escape, then turn bare URLs into links."""
    out, pos = [], 0
    for m in _URL.finditer(text):
        out.append(html.escape(text[pos:m.start()]))
        url = m.group(0)
        out.append(
            f'<a href="{html.escape(url, quote=True)}" style="color:{TEAL};text-decoration:underline;'
            f'word-break:break-all">{html.escape(url)}</a>'
        )
        pos = m.end()
    out.append(html.escape(text[pos:]))
    return "".join(out)


def _blocks(body: str, rtl: bool) -> str:
    align = "right" if rtl else "left"
    parts = []
    for para in re.split(r"\n\s*\n", body.strip()):
        lines = para.split("\n")
        steps = [_STEP.match(line) for line in lines]
        if any(steps):
            items = []
            for line, m in zip(lines, steps):
                if m:
                    items.append(
                        f'<tr><td valign="top" style="padding:4px 0;width:30px">'
                        f'<span style="display:inline-block;width:22px;height:22px;line-height:22px;border-radius:11px;'
                        f'background:{GOLD};color:{INK};font-size:12px;font-weight:700;text-align:center">{m.group(1)}</span></td>'
                        f'<td style="padding:4px 0;color:{INK};font-size:15px;line-height:1.7;text-align:{align}">{_inline(m.group(2))}</td></tr>'
                    )
                else:
                    weight = 700 if line.rstrip().endswith((":", "：")) else 400
                    items.append(
                        f'<tr><td colspan="2" style="padding:6px 0 2px;color:{INK};font-size:15px;font-weight:{weight};'
                        f'line-height:1.7;text-align:{align}">{_inline(line)}</td></tr>'
                    )
            parts.append(
                f'<table role="presentation" cellpadding="0" cellspacing="0" width="100%" '
                f'style="margin:0 0 16px;border-collapse:collapse">{"".join(items)}</table>'
            )
        else:
            text = "<br>".join(_inline(line) for line in lines)
            parts.append(
                f'<p style="margin:0 0 16px;color:{INK};font-size:15px;line-height:1.8;text-align:{align}">{text}</p>'
            )
    return "".join(parts)


def branded(lang: str, title: str, body: str) -> tuple[str, str]:
    """Return (plain text, HTML) for `body`; both carry the Facebook + Instagram footer."""
    lang = "ar" if lang == "ar" else "en"
    rtl = lang == "ar"
    d = "rtl" if rtl else "ltr"
    align = "right" if rtl else "left"
    follow = FOLLOW[lang]
    follow_ig = FOLLOW_IG[lang]
    text = (f"{body.rstrip()}\n\n—\n{follow}: {FACEBOOK_URL}\n"
            f"{follow_ig}: {INSTAGRAM_URL}\n{SITE_URL}\n")
    page = f"""<!doctype html>
<html lang="{lang}" dir="{d}">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light only"><title>{html.escape(title)}</title></head>
<body style="margin:0;padding:0;background:{CREAM};font-family:{FONT}">
<table role="presentation" cellpadding="0" cellspacing="0" width="100%" style="background:{CREAM}">
<tr><td align="center" style="padding:24px 12px">
<table role="presentation" cellpadding="0" cellspacing="0" width="100%" dir="{d}"
 style="max-width:560px;background:{SURFACE};border:1px solid {LINE};border-radius:16px;overflow:hidden">
<tr><td align="center" style="background:{TEAL};background-image:linear-gradient(200deg,#11706A,{TEAL_LO});padding:22px 24px;border-bottom:2px solid {GOLD}">
<img src="{LOGO_URL}" width="120" height="88" alt="{'تبيان' if rtl else 'Tibyan'}" style="display:block;border:0;width:120px;height:auto">
</td></tr>
<tr><td style="padding:28px 28px 8px;text-align:{align}">
<h1 style="margin:0 0 18px;color:{TEAL};font-size:21px;line-height:1.5;font-weight:700">{html.escape(title)}</h1>
{_blocks(body, rtl)}
</td></tr>
<tr><td style="padding:16px 28px 24px;border-top:1px solid {LINE};text-align:{align};color:{INK_2};font-size:13px;line-height:1.8">
<a href="{SITE_URL}" style="color:{TEAL}">altibyan.app</a> ·
<a href="{FACEBOOK_URL}" style="color:{TEAL}">{follow}</a> ·
<a href="{INSTAGRAM_URL}" style="color:{TEAL}">{follow_ig}</a>
</td></tr>
</table>
</td></tr></table>
</body></html>"""
    return text, page
