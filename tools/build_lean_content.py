"""Make the bundled content database light to install (run after build_content_db.py).

1. Word timings move out of content.db into one pack per reciter, downloaded
   with that reciter's audio (lib/features/audio/word_timing_packs.dart).
   Only reciters whose timings are already published (data/timing/reciters.json
   "publish": true) move: the others' licence keeps them inside the app. Each
   pack is the TimingPack format of timing_updates.dart (verse and word timings
   of every surah), named by its SHA-256, written to data/word_timing_packs/ and
   listed in lib/features/audio/word_timing_specs.dart. Upload the files to
   https://tibyan.ahmedhelal.dev/mirror/packs/timing/ (sha256sums.txt beside them).
2. content.db is cut into parts under assets/content_db/ with a manifest
   (bytes, SHA-256, parts), so the app copies it out a few MB at a time.

assets/db/content.db stays the whole (lean) database for tools and tests; only
assets/content_db/ is bundled. Running it again with nothing left to move only
re-cuts the parts.

Usage: python3 tools/build_lean_content.py
"""
import gzip
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / 'assets' / 'db' / 'content.db'
PARTS = ROOT / 'assets' / 'content_db'
PACKS = ROOT / 'data' / 'word_timing_packs'
SPECS = ROOT / 'lib' / 'features' / 'audio' / 'word_timing_specs.dart'
RECITERS = ROOT / 'data' / 'timing' / 'reciters.json'
PART_BYTES = 4 * 1024 * 1024


def published():
    """Reciter id -> slug of every recitation whose timings are published."""
    doc = json.loads(RECITERS.read_text(encoding='utf-8'))
    return {r['id']: r['slug'] for r in doc['reciters'] if r.get('publish') is True}


def pack_bytes(db, reciter, slug):
    version = db.execute(
        "SELECT value FROM meta WHERE key = ?", (f'timing_version:{slug}',)
    ).fetchone()
    folder = db.execute('SELECT folder_url FROM reciter WHERE id = ?', (reciter,)).fetchone()[0]
    words = {}
    for surah, ayah, word, start, end in db.execute(
        'SELECT surah, ayah, word, start_ms, end_ms FROM word_timing '
        'WHERE reciter = ? ORDER BY surah, ayah, word',
        (reciter,),
    ):
        words.setdefault((surah, ayah), []).append([word, start, end])
    surahs = {}
    for surah, ayah, start, end in db.execute(
        'SELECT surah, ayah, start_ms, end_ms FROM ayah_timing '
        'WHERE reciter = ? ORDER BY surah, ayah',
        (reciter,),
    ):
        surahs.setdefault(str(surah), []).append([ayah, start, end, words.pop((surah, ayah), [])])
    if words:
        raise SystemExit(f'reciter {reciter}: word timings without a verse timing: {sorted(words)[:3]}')
    for surah, verses in surahs.items():  # as TimingPack.decode checks
        for ayah, start, end, ws in verses:
            if end <= start or any(we <= w0 for _, w0, we in ws):
                raise SystemExit(f'reciter {reciter}: span not forward in {surah}:{ayah}')
    doc = {
        'format': 1,
        'slug': slug,
        'reciter_id': reciter,
        'version': int(version[0]) if version else 1,
        'folder_url': folder,
        'surahs': surahs,
    }
    raw = json.dumps(doc, separators=(',', ':')).encode()
    return gzip.compress(raw, compresslevel=9, mtime=0)


def move_word_timings(db):
    moved = {}
    have = {r for (r,) in db.execute('SELECT DISTINCT reciter FROM word_timing')}
    for reciter, slug in sorted(published().items()):
        if reciter not in have:
            continue
        data = pack_bytes(db, reciter, slug)
        sha = hashlib.sha256(data).hexdigest()
        name = f'words-{reciter}-{sha[:12]}.json.gz'
        PACKS.mkdir(parents=True, exist_ok=True)
        (PACKS / name).write_bytes(data)
        moved[reciter] = (name, sha, len(data))
    if not moved:
        return
    for old in PACKS.glob('words-*.json.gz'):
        if old.name not in {m[0] for m in moved.values()}:
            old.unlink()
    marks = ','.join('?' * len(moved))
    db.execute(f'DELETE FROM word_timing WHERE reciter IN ({marks})', list(moved))
    db.commit()
    db.execute('VACUUM')
    (PACKS / 'sha256sums.txt').write_text(
        ''.join(f'{sha}  {name}\n' for name, sha, _ in moved.values())
    )
    lines = [
        '// GENERATED by tools/build_lean_content.py. Do not edit.',
        '',
        "part of 'word_timing_packs.dart';",
        '',
        '/// The word-timing pack of each reciter whose word timings are not in',
        '/// content.db, by reciter id.',
        'const wordTimingSpecs = <int, WordTimingSpec>{',
    ]
    for reciter, (name, sha, size) in sorted(moved.items()):
        lines += [
            f'  {reciter}: WordTimingSpec(',
            f"    file: '{name}',",
            f"    sha256: '{sha}',",
            f'    bytes: {size},',
            '  ),',
        ]
    lines += ['};', '']
    SPECS.write_text('\n'.join(lines))
    print(f'moved word timings of {sorted(moved)} to {PACKS}')


def cut_parts():
    data = DB.read_bytes()
    PARTS.mkdir(parents=True, exist_ok=True)
    for old in PARTS.iterdir():
        old.unlink()
    parts = []
    for i in range(0, len(data), PART_BYTES):
        name = f'part-{i // PART_BYTES:03d}.bin'
        (PARTS / name).write_bytes(data[i:i + PART_BYTES])
        parts.append(name)
    manifest = {
        'bytes': len(data),
        'sha256': hashlib.sha256(data).hexdigest(),
        'parts': parts,
    }
    (PARTS / 'manifest.json').write_text(json.dumps(manifest, indent=1) + '\n')
    print(f'content.db: {len(data)} bytes in {len(parts)} parts')


def main():
    db = sqlite3.connect(DB)
    move_word_timings(db)
    db.close()
    cut_parts()


if __name__ == '__main__':
    main()
