#!/usr/bin/env python3
"""Draws the watch apps' art in the «ليل هندسي» look (handoff 07):

- the Wear OS background as a vector drawable (teal radial gradient to
  near-black with the app's Girih pattern at 13%: the geometry of
  GirihPainter in lib/core/theme/ornaments.dart),
- the watch icon «لوجو تبيان على تيل» (assets/brand/tibyan_logo.svg in
  cream on the same ground) for watchOS (1024, opaque), the Wear OS
  launcher (legacy, round and adaptive mipmaps) and the store exports.

Needs rsvg-convert and magick (Homebrew). Run from the repo root:
    python3 tools/watch/make_watch_art.py
"""
import math
import re
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEAL, DEEP, NIGHT = "#0e5f58", "#06302c", "#020c0b"
CREAM, GOLD = "#f4ecd8", "#d9b266"


def star(cx, cy, r, points=8, inner=0.765):
    """starPath() of ornaments.dart."""
    pts = []
    for i in range(points * 2):
        rr = r if i % 2 == 0 else r * inner
        a = -math.pi / 2 + i * math.pi / points
        pts.append((cx + math.cos(a) * rr, cy + math.sin(a) * rr))
    return "M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z"


def girih(w, h, cell):
    """GirihPainter.paint(): an 8-point star on every grid point and a
    4-point star in every cell's middle."""
    paths = []
    y = 0.0
    while y < h + cell:
        x = 0.0
        while x < w + cell:
            paths.append(star(x, y, cell * 0.5, inner=0.72))
            paths.append(star(x + cell / 2, y + cell / 2, cell * 0.22, points=4, inner=0.45))
            x += cell
        y += cell
    return paths


def wear_background():
    size, cell = 454, 112
    d = "".join(girih(size, size, cell))
    radius = math.hypot(size / 2, size * 0.7)
    xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/watch/make_watch_art.py: teal night with the Girih at 13%. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="454dp" android:height="454dp"
    android:viewportWidth="{size}" android:viewportHeight="{size}">
    <path android:pathData="M0,0h{size}v{size}h-{size}z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial"
                android:centerX="{size/2}" android:centerY="{size*0.3:.1f}"
                android:gradientRadius="{radius:.1f}">
                <item android:offset="0" android:color="{TEAL}"/>
                <item android:offset="0.58" android:color="{DEEP}"/>
                <item android:offset="1" android:color="{NIGHT}"/>
            </gradient>
        </aapt:attr>
    </path>
    <path android:pathData="{d}"
        android:strokeColor="#21F4ECD8" android:strokeWidth="2"/>
</vector>
"""
    out = ROOT / "android/wear/src/main/res/drawable/watch_background.xml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(xml)


def logo_paths():
    svg = (ROOT / "assets/brand/tibyan_logo.svg").read_text()
    return re.findall(r'<path[^>]*\sd="([^"]+)"', svg)


def icon_svg(size=1024, logo=True, ground=True, logo_width=0.6, ring=True):
    """The icon on a square: full bleed, the logo inside the circle."""
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 1024 1024">']
    if ground:
        parts.append(f"""<defs><radialGradient id="g" cx="512" cy="400" r="760" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="{TEAL}"/><stop offset=".58" stop-color="{DEEP}"/><stop offset="1" stop-color="{NIGHT}"/></radialGradient></defs>
<rect width="1024" height="1024" fill="url(#g)"/>
<g fill="none" stroke="{CREAM}" stroke-opacity=".13" stroke-width="3">{''.join(f'<path d="{p}"/>' for p in girih(1024, 1024, 256))}</g>
""")
        if ring:
            parts.append(f'<circle cx="512" cy="512" r="452" fill="none" stroke="{GOLD}" stroke-opacity=".8" stroke-width="10"/>')
    if logo:
        w = 1024 * logo_width
        s = w / 1392
        h = 1019 * s
        parts.append(f'<g transform="translate({(1024-w)/2:.1f},{(1024-h)/2 + 10:.1f}) scale({s:.4f})" fill="{CREAM}">')
        parts += [f'<path d="{p}"/>' for p in logo_paths()]
        parts.append("</g>")
    parts.append("</svg>")
    return "".join(parts)


def render(svg, out, size, opaque=False):
    out.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", suffix=".svg", delete=False) as f:
        f.write(svg)
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), f.name, "-o", str(out)], check=True)
    if opaque:
        subprocess.run(["magick", str(out), "-background", NIGHT, "-alpha", "remove", "-alpha", "off", str(out)], check=True)


def tile_background():
    # Tiles take bitmaps: the same ground as a PNG.
    render(icon_svg(logo=False, ring=False), ROOT / "android/wear/src/main/res/drawable-nodpi/tile_background.png", 454, opaque=True)


def icons():
    full = icon_svg()
    render(full, ROOT / "apple/TibyanWatch/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png", 1024, opaque=True)
    render(full, ROOT / "docs/brand/appstore/watch/icon-1024.png", 1024, opaque=True)
    render(full, ROOT / "docs/brand/play/wear/icon-512.png", 512, opaque=True)
    res = ROOT / "android/wear/src/main/res"
    for name, scale in {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}.items():
        d = res / f"mipmap-{name}"
        render(full, d / "ic_launcher.png", int(48 * scale), opaque=True)
        render(full, d / "ic_launcher_round.png", int(48 * scale), opaque=True)
        # Adaptive layers are 108dp; the logo stays in the 66dp safe circle.
        render(icon_svg(ground=False, logo_width=0.5), d / "ic_launcher_foreground.png", int(108 * scale))
        render(icon_svg(logo=False, ring=False), d / "ic_launcher_background.png", int(108 * scale), opaque=True)
    any_dpi = res / "mipmap-anydpi-v26"
    any_dpi.mkdir(parents=True, exist_ok=True)
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
"""
    for n in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (any_dpi / n).write_text(adaptive)


if __name__ == "__main__":
    wear_background()
    tile_background()
    icons()
